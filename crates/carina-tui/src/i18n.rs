pub fn format(locale: Locale, id: MessageId, args: &[(&str, &str)]) -> String {
    let mut rendered = text(locale, id).to_owned();
    for (name, value) in args {
        rendered = rendered.replace(&format!("{{{name}}}"), &strip_controls(value));
    }
    debug_assert!(
        placeholders(&rendered).is_empty(),
        "missing i18n parameter for {locale:?} {id:?}"
    );
    rendered
}

fn placeholders(value: &str) -> Vec<&str> {
    let mut names = Vec::new();
    let mut rest = value;
    while let Some(open) = rest.find('{') {
        rest = &rest[open + 1..];
        let Some(close) = rest.find('}') else { break };
        names.push(&rest[..close]);
        rest = &rest[close + 1..];
    }
    names
}

pub fn count(locale: Locale, one: MessageId, other: MessageId, value: usize) -> String {
    let id = if matches!(locale, Locale::En | Locale::Es | Locale::Fr) && value == 1 {
        one
    } else {
        other
    };
    format(locale, id, &[("count", &value.to_string())])
}

pub fn tool_group_title(locale: Locale, kind: ToolKind, count: usize, running: bool) -> String {
    let (active, settled) = tool_group_verbs(locale, kind);
    let (singular, plural) = tool_group_nouns(locale, kind);
    let verb = if running { active } else { settled };
    let noun = if count == 1 { singular } else { plural };
    match locale {
        Locale::ZhHans => format!("{verb}{count} 个{noun}"),
        Locale::ZhHant => format!("{verb}{count} 個{noun}"),
        Locale::Ja => format!("{noun}{count}件を{verb}"),
        Locale::Ko => format!("{noun} {count}개 {verb}"),
        Locale::En | Locale::Es | Locale::Fr => format!("{verb} {count} {noun}"),
    }
}

pub fn tool_group_failure(locale: Locale, count: usize) -> String {
    match (locale, count) {
        (_, 0) => String::new(),
        (Locale::En, count) => format!("{count} failed"),
        (Locale::ZhHans, count) => format!("{count} 个失败"),
        (Locale::ZhHant, count) => format!("{count} 個失敗"),
        (Locale::Ja, count) => format!("{count}件失敗"),
        (Locale::Ko, count) => format!("{count}개 실패"),
        (Locale::Es, 1) => "1 falló".into(),
        (Locale::Es, count) => format!("{count} fallaron"),
        (Locale::Fr, 1) => "1 échec".into(),
        (Locale::Fr, count) => format!("{count} échecs"),
    }
}

