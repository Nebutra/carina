fn localized_pair(locale: Locale, copy: [&'static str; 14]) -> (&'static str, &'static str) {
    let offset = locale_index(locale) * 2;
    (copy[offset], copy[offset + 1])
}

fn localized_nouns(locale: Locale, copy: [&'static str; 12]) -> (&'static str, &'static str) {
    let offset = match locale {
        Locale::En => 0,
        Locale::ZhHans => 2,
        Locale::ZhHant => 4,
        Locale::Ja => 6,
        Locale::Ko => 7,
        Locale::Es => 8,
        Locale::Fr => 10,
    };
    let plural_offset = if matches!(locale, Locale::Ja | Locale::Ko) {
        0
    } else {
        1
    };
    (copy[offset], copy[offset + plural_offset])
}

fn locale_index(locale: Locale) -> usize {
    match locale {
        Locale::En => 0,
        Locale::ZhHans => 1,
        Locale::ZhHant => 2,
        Locale::Ja => 3,
        Locale::Ko => 4,
        Locale::Es => 5,
        Locale::Fr => 6,
    }
}

pub fn strip_controls(value: &str) -> Cow<'_, str> {
    if value
        .chars()
        .all(|ch| ch == '\n' || ch == '\t' || !ch.is_control())
    {
        Cow::Borrowed(value)
    } else {
        Cow::Owned(
            value
                .chars()
                .filter(|ch| *ch == '\n' || *ch == '\t' || !ch.is_control())
                .collect(),
        )
    }
}

