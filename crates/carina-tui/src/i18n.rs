use std::borrow::Cow;

use crate::tool_projection::ToolKind;

#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub enum Notice {
    #[default]
    Empty,
    Raw(String),
    Localized {
        id: MessageId,
        args: Vec<(String, String)>,
        run_owner: Option<String>,
    },
}

impl Notice {
    pub fn localized(id: MessageId) -> Self {
        Self::Localized {
            id,
            args: Vec::new(),
            run_owner: None,
        }
    }

    pub fn localized_with(
        id: MessageId,
        args: impl IntoIterator<Item = (impl Into<String>, impl Into<String>)>,
    ) -> Self {
        Self::Localized {
            id,
            args: args
                .into_iter()
                .map(|(name, value)| (name.into(), value.into()))
                .collect(),
            run_owner: None,
        }
    }

    pub fn localized_for_run(
        id: MessageId,
        run_id: impl Into<String>,
        args: impl IntoIterator<Item = (impl Into<String>, impl Into<String>)>,
    ) -> Self {
        Self::Localized {
            id,
            args: args
                .into_iter()
                .map(|(name, value)| (name.into(), value.into()))
                .collect(),
            run_owner: Some(run_id.into()),
        }
    }

    pub fn clear(&mut self) {
        *self = Self::Empty;
    }
    pub fn is_empty(&self) -> bool {
        matches!(self, Self::Empty)
    }

    pub fn render(&self, locale: Locale) -> Cow<'_, str> {
        let rendered = match self {
            Self::Empty => Cow::Borrowed(""),
            Self::Raw(value) => Cow::Borrowed(value.as_str()),
            Self::Localized { id, args, .. } => {
                let refs = args
                    .iter()
                    .map(|(name, value)| (name.as_str(), value.as_str()))
                    .collect::<Vec<_>>();
                Cow::Owned(format(locale, *id, &refs))
            }
        };
        crate::glyphs::Glyphs::detect().sanitize_free_text(rendered)
    }

    pub fn raw(&self) -> &str {
        match self {
            Self::Raw(value) => value,
            _ => "",
        }
    }

    pub fn raw_starts_with(&self, prefix: &str) -> bool {
        self.raw().starts_with(prefix)
    }

    pub fn raw_eq(&self, value: &str) -> bool {
        self.raw() == value
    }

    pub fn is_owned_by_run(&self, run_id: &str) -> bool {
        matches!(self, Self::Localized { run_owner: Some(owner), .. } if owner == run_id)
    }

    pub fn is_localized(&self, expected: MessageId) -> bool {
        matches!(self, Self::Localized { id, .. } if *id == expected)
    }
}

impl From<String> for Notice {
    fn from(value: String) -> Self {
        if value.is_empty() {
            Self::Empty
        } else {
            Self::Raw(value)
        }
    }
}

impl From<&str> for Notice {
    fn from(value: &str) -> Self {
        value.to_owned().into()
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum Locale {
    En,
    ZhHans,
    ZhHant,
    Ja,
    Ko,
    Es,
    Fr,
}

impl Locale {
    pub const ALL: [Self; 7] = [
        Self::En,
        Self::ZhHans,
        Self::ZhHant,
        Self::Ja,
        Self::Ko,
        Self::Es,
        Self::Fr,
    ];

    pub fn from_product_id(value: &str) -> Option<Self> {
        match value {
            "en" => Some(Self::En),
            "zh" | "zh-Hans" | "zh-CN" | "zh-SG" => Some(Self::ZhHans),
            "zh-Hant" | "zh-TW" | "zh-HK" | "zh-MO" => Some(Self::ZhHant),
            "ja" | "ja-JP" => Some(Self::Ja),
            "ko" | "ko-KR" => Some(Self::Ko),
            "es" | "es-ES" => Some(Self::Es),
            "fr" | "fr-FR" => Some(Self::Fr),
            _ => None,
        }
    }

    pub const fn product_id(self) -> &'static str {
        match self {
            Self::En => "en",
            Self::ZhHans => "zh-Hans",
            Self::ZhHant => "zh-Hant",
            Self::Ja => "ja",
            Self::Ko => "ko",
            Self::Es => "es",
            Self::Fr => "fr",
        }
    }
}

